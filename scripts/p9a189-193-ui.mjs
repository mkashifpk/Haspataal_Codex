import fs from 'node:fs';
import assert from 'node:assert/strict';
import {session,expect,help,capture} from './clinical-test-kit.mjs';

const dir='docs/phase-p9a-2026-11-06/';
const file='artifacts/p9a189-193-journey.json';
assert(!fs.existsSync(file),'Reconcile the original writes before continuing. Never rerun the guarded journey.');
const source=JSON.parse(fs.readFileSync(dir+'189-incident-result.json')).body.data;
assert(source.description.includes('SYNTHETIC P9A189'));
const journal={incident:source.incident_number,columnCode:`p9a193_${Date.now()}`,pending:null,passes:[]};
const save=()=>fs.writeFileSync(file,JSON.stringify(journal,null,2));
save();
const s=await session('p9a189-193-ui','demo.quality');
const navigate=async id=>{await s.p.getByRole('navigation').locator(`[data-screen-target="${id}"]`).click();return s.p.locator(`[data-screen="${id}"]`);};
const button=(root,name)=>root.getByRole('button',{name,exact:true});
const read=path=>s.native('api',{method:'GET',path});
const done=async(id,label)=>{await capture(s,id);journal.passes.push(id);save();s.pass(label);};
async function preview(root,name){
  const traceCount=(await s.trace()).requests.length;
  await button(root,name).click();
  await expect(root).toContainText('PDF opened.');
  const requests=(await s.trace()).requests.slice(traceCount);
  assert(requests.some(r=>r.method==='GET'&&r.path.includes('/pdf')&&r.status===200));
  for(const p of s.app.windows())if(p!==s.p&&p.url().startsWith('data:application/pdf'))await p.close();
}
try {
  // Open only the fresh, explicitly synthetic ADR source returned by DEV.
  const adr=await navigate('adr_report');
  const picker=adr.getByLabel('ADR incident',{exact:true});
  await picker.selectOption(String(source.incident_id));
  await expect(adr).toContainText('Pre-filled draft');
  await expect(adr).toContainText('Paracetamol 500mg');
  const path=`/incidents/${source.incident_id}/adr-report`;
  assert.equal((await read(path)).saved,false);
  await button(adr,'Edit report details').click();
  await adr.locator('[name="pack_size"]').fill('SYNTHETIC DEV pack only');
  await adr.locator('[name="manufacturer_name"]').fill('SYNTHETIC DEV sample manufacturer');
  await adr.getByLabel('Batch source',{exact:true}).selectOption('stock');
  const batch=adr.getByLabel('Batch from stock',{exact:true});
  const option=batch.locator('option').filter({hasText:'B-PCM-500-1'});
  await expect(option).toHaveCount(1);
  await batch.selectOption(await option.getAttribute('value'));
  await help(s,batch,'Adverse drug reaction report');
  await adr.locator('input[data-help="adr.save"]').check();
  await s.fault({failPath:path,failMethod:'PUT',once:true});
  journal.pending='First ADR PUT. Read current draft if reply is lost. Never replay.';save();
  await button(adr,'Save ADR report').click();
  await expect(button(adr,'Read current result')).toBeEnabled();
  await expect(button(adr,'Retry original request')).toHaveCount(0);
  await button(adr,'Read current result').click();
  await button(adr,'Result reviewed; return to draft').click();
  await expect(adr).toContainText('Saved ADR report');
  journal.adrSaved=await read(path);
  assert(journal.adrSaved.saved&&journal.adrSaved.contact_stamp?.text);
  assert.equal(journal.adrSaved.batch_number,'B-PCM-500-1');
  assert.equal(journal.adrSaved.expiry_date,'2028-10-05');
  journal.pending=null;save();
  await preview(adr,'Preview ADR report');
  await button(adr,'Mark as sent').click();
  await adr.locator('[name="recipient"]').selectOption('DRAP');
  await adr.locator('[name="sent_on"]').fill('2026-11-09');
  await adr.locator('[name="reference"]').fill('SYNTHETIC P9A189 tabletop only, no report transmitted');
  await adr.locator('input[data-help="adr.save"]').check();
  await s.fault({failPath:`${path}/submissions`,failMethod:'POST',once:true});
  journal.pending='One synthetic sending record. No external transmission. Original-key retry only.';save();
  await button(adr,'Record sending').click();
  await expect(button(adr,'Retry original request')).toBeEnabled();
  await button(adr,'Retry original request').click();
  await expect(adr).toContainText('report fields are locked');
  await expect(button(adr,'Edit report details')).toHaveCount(0);
  journal.adrSent=await read(path);
  assert.equal(journal.adrSent.submissions.length,1);
  assert.equal(journal.adrSent.submissions[0].recipient,'DRAP');
  journal.pending=null;save();
  await button(adr,'Mark as sent').click();
  await expect(adr.locator('[name="recipient"] option')).toHaveCount(2);
  await expect(adr.locator('[name="recipient"] option[value="DRAP"]')).toHaveCount(0);
  await button(adr,'Cancel unsent changes').click();
  await done('adr_report','ADR prefill, actual named stock batch, saved reporting stamp, lost PUT read-only recovery, official PDF and one synthetic submission with original replay and locked form.');

  const transfusion=await navigate('blood_registers');
  await expect(transfusion.getByRole('heading',{name:'Issue turnaround by urgency'})).toBeVisible();
  await expect(transfusion.locator('.metric-grid')).toContainText('—');
  await expect(transfusion).toContainText('Each patient printed is logged');
  for(const name of ['statistics','transfusion register','reaction register','storage checks'])await preview(transfusion,'Preview '+name);
  await button(transfusion,'Read blood units').click();
  await expect(transfusion).toContainText('No blood units are recorded.');
  await help(s,transfusion.locator('input[name="date_from"]'),'Blood transfusion: registers and monitoring');
  await done('blood_registers','Server period statistics, missing rates as dashes, historical unit read, all four PDF previews and audit notice.');

  const center=await navigate('blood_center_registers');
  await expect(center.getByRole('heading',{name:'Infection screens'})).toBeVisible();
  await expect(center).toContainText('Opening a donation is logged');
  await button(center,'Read donations for this period').click();
  await expect(center).toContainText('No donations for this period.');
  await preview(center,'Preview blood center registers');
  await help(s,center.locator('input[name="date_from"]'),'Blood center: return and registers');
  await done('blood_center_registers','Computed last-quarter blood center return, authorized period donation list, independent PDF and contextual help.');

  const obstetric=await navigate('obstetric_register');
  await expect(obstetric).toContainText('No high-risk assessments for this period.');
  await button(obstetric,'Newborns').click();
  await expect(obstetric).toContainText('No newborns for this period.');
  await button(obstetric,'Labour register').click();
  await expect(obstetric.getByRole('checkbox',{name:'Draft entries still to sign'})).toBeChecked();
  await expect(obstetric).toContainText('No draft entries for this period.');
  await obstetric.getByRole('checkbox',{name:'Draft entries still to sign'}).uncheck();
  await expect(obstetric).toContainText('No delivery entries for this period.');
  for(const name of ['high-risk register','labour register'])await preview(obstetric,'Preview '+name);
  await help(s,obstetric.locator('input[name="date_from"]'),'High-risk obstetric patients and newborns');
  await done('obstetric_register','High-risk, newborn, draft and all-delivery period reads, official PDFs, patient access notice and F1.');

  const columns=await navigate('labour_register_columns');
  const list=()=>read('/maternity/labour-register/columns?include_inactive=true');
  const initial=await list();
  assert(initial.some(x=>x.source));
  const sourced=initial.find(x=>x.is_active&&x.source);
  await expect(columns).toContainText(sourced.source);
  assert(!initial.some(x=>x.code===journal.columnCode));
  await button(columns,'Add column').click();
  await columns.locator('[name="code"]').fill(journal.columnCode);
  await columns.getByLabel('Kind',{exact:true}).selectOption('Choice');
  await columns.locator('[name="label"]').fill('SYNTHETIC P9A193 training column only');
  await columns.locator('[name="choices"]').fill('Synthetic example A\nSynthetic example B');
  await help(s,columns.locator('[name="label"]'),'Labour register: the columns');
  await columns.locator('input[data-help="lc.save"]').check();
  await s.fault({failPath:'/maternity/labour-register/columns',failMethod:'POST',once:true});
  journal.pending='Create own synthetic column, retry original key only.';save();
  await button(columns,'Save column').click();
  await expect(button(columns,'Retry original request')).toBeEnabled();
  await button(columns,'Retry original request').click();
  const own=columns.getByRole('row').filter({hasText:journal.columnCode});
  await expect(own).toBeVisible();
  journal.columnCreated=(await list()).find(x=>x.code===journal.columnCode);
  assert(journal.columnCreated?.is_active);
  journal.pending=null;save();
  await own.getByRole('button',{name:'Change column',exact:true}).click();
  await expect(columns.locator('[name="code"]')).toHaveCount(0);
  await expect(columns.getByLabel('Kind',{exact:true})).toHaveCount(0);
  await expect(columns.getByLabel('Section',{exact:true})).toHaveCount(0);
  await columns.locator('[name="choices"]').fill('Synthetic example C');
  await columns.locator('[name="is_active"]').uncheck();
  await columns.locator('input[data-help="lc.save"]').check();
  await s.fault({failPath:`/maternity/labour-register/columns/${journal.columnCreated.field_id}`,failMethod:'PATCH',once:true});
  journal.pending='Append one choice and switch own column off. GET-only reconciliation.';save();
  await button(columns,'Save column').click();
  await expect(button(columns,'Read current result')).toBeEnabled();
  await expect(button(columns,'Retry original request')).toHaveCount(0);
  await button(columns,'Read current result').click();
  await button(columns,'Result reviewed; return to draft').click();
  await expect(own).toHaveCount(0);
  journal.columnRetired=(await list()).find(x=>x.code===journal.columnCode);
  assert.equal(journal.columnRetired.row_version,journal.columnCreated.row_version+1);
  assert.equal(journal.columnRetired.is_active,false);
  assert.deepEqual(journal.columnRetired.choices,[...journal.columnCreated.choices,'Synthetic example C']);
  journal.pending=null;save();
  await columns.getByRole('checkbox',{name:'Include switched-off columns'}).check();
  await expect(own).toContainText('Switched off');
  await done('labour_register_columns','Source labels, fresh choice column, original-key replay, immutable identity, append-only choices, switched-off version with lost PATCH and read-only reconciliation.');

  const calls=(await s.trace()).requests;
  assert(calls.some(r=>r.path.includes('/maternity/labour-register?')&&r.path.includes('status=Draft')&&r.status===200));
  assert(calls.some(r=>r.path.includes('/blood/units?')&&r.path.includes('status=Transfused')&&r.status===200));
  const writes=calls.filter(r=>r.method!=='GET');
  assert.equal(writes.length,6);
  for(const match of ['/adr-report/submissions','/maternity/labour-register/columns']){
    const pair=writes.filter(r=>r.method==='POST'&&r.path.endsWith(match));
    assert.equal(pair.length,2);assert.equal(pair[0].key,pair[1].key);assert.deepEqual(pair[0].body,pair[1].body);assert.equal(pair[1].replay,'true');
  }
  journal.writes=writes;journal.passed=true;save();s.j.passed=true;
} catch(error){journal.error=error.stack;save();s.j.error=error.stack;throw error;}
finally{await s.close();}
