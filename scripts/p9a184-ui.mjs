import fs from "node:fs";
import assert from "node:assert/strict";
import { session, expect, help, capture } from "./clinical-test-kit.mjs";

const file = "artifacts/p9a184-journey.json";
assert(!fs.existsSync(file), "Reconcile the original writes. Do not rerun the guarded journey.");
const previous = JSON.parse(fs.readFileSync("docs/phase-p9a-2026-11-06/183-followup-ui-journey.json"));
const id = previous.anonymous.feedback_id;
const journal = { id, number: previous.anonymous.feedback_number, pending: null };
const save = () => fs.writeFileSync(file, JSON.stringify(journal, null, 2));
save();
let s;
try {
  s = await session("p9a184-ui", "demo.quality");
  const path = `/patient-feedback/${id}`;
  const current = () => s.native("api", {method:"GET", path});
  const initial = await current();
  assert.equal(initial.reviewed_at, null);
  assert.equal(initial.actions.length, 0);
  assert.equal(initial.review_pending, true);
  await s.p.getByRole("navigation").locator('[data-screen-target="patient_feedback"]').click();
  const root = s.p.locator('[data-screen="patient_feedback"]');
  const exact = name => root.getByRole("button", {name, exact:true});
  await expect(root.locator('[name="review_pending"]')).toBeChecked();
  const row = root.getByRole("row").filter({hasText:journal.number});
  await expect(row).toHaveClass("feedback-dissatisfied");
  await exact(journal.number).click();
  const selected = root.getByRole("article", {name:"Selected response"});
  await expect(selected).toContainText("Not named");
  await expect(selected).toContainText("Waiting time is too long");
  await exact("Review response").click();
  const text = "SYNTHETIC P9A184: tabletop review of the waiting-time response. No real complaint or compliance assertion.";
  const reviewField = selected.locator('textarea[name="action_taken"]');
  await reviewField.fill(text);
  await help(s, reviewField, "Patient feedback: review and actions");
  await expect(reviewField).toHaveValue(text);
  await selected.locator('input[data-help="pfr.confirm"]').check();
  await s.fault({failPath: `${path}/review`, failMethod:"POST", once:true});
  journal.pending = "Final review. Reconcile by GET only if the reply is lost."; save();
  await exact("Save final review").click();
  await expect(exact("Read current result")).toBeEnabled();
  await expect(exact("Retry original request")).toHaveCount(0);
  await exact("Read current result").click();
  await exact("Result reviewed; return to draft").click();
  await expect(selected).toContainText(text);
  await expect(exact("Raise action")).toBeVisible();
  journal.review = await current();
  assert.equal(journal.review.review_action,text);
  assert(journal.review.reviewed_at);
  assert.equal(journal.review.review_pending,false);
  journal.pending = null; save();
  await exact("Raise action").click();
  await selected.locator('[name="description"]').fill("SYNTHETIC P9A184: rehearse giving a wait estimate at the training desk.");
  const owner = selected.locator('select[name="owner_user_id"]');
  await owner.selectOption(await owner.locator("option").filter({hasText:"Nurse Hina"}).getAttribute("value"));
  const department = selected.locator('select[name="department_id"]');
  await department.selectOption(await department.locator("option").filter({hasText:"General Medicine"}).getAttribute("value"));
  await selected.locator('input[name="due_date"]').fill("2026-11-20");
  await selected.locator('input[data-help="pfr.confirm"]').check();
  await s.fault({failPath:`${path}/actions`,failMethod:"POST",once:true});
  journal.pending = "One named action. Retry original frozen key and body only."; save();
  await exact("Assign action").click();
  await expect(exact("Retry original request")).toBeEnabled();
  await exact("Retry original request").click();
  await expect(selected).toContainText("Nurse Hina");
  journal.result = await current();
  assert.equal(journal.result.actions.length,1);
  assert.equal(journal.result.actions[0].owner_name,"Nurse Hina");
  assert.equal(journal.result.actions[0].department_name,"General Medicine");
  journal.pending = null; save();
  await expect(exact("Review response")).toHaveCount(0);
  await root.locator('[name="review_pending"]').uncheck();
  await exact("Apply feedback filters").click();
  await expect(exact(journal.number)).toBeVisible();
  await expect(exact(previous.named.feedback_number)).toBeVisible();
  const firstRow = root.locator("tbody tr").first();
  await expect(firstRow).toContainText(journal.number);
  await expect(root.getByRole("heading", {name:"Period summary"})).toBeVisible();
  await expect(root.getByRole("meter", {name:"Waiting time is too long"})).toBeVisible();
  await exact(previous.named.feedback_number).click();
  await expect(selected).toContainText(previous.named.patient_name);
  await exact("Preview blank feedback form").click();
  await expect(root).toContainText("PDF opened.");
  for (const p of s.app.windows()) if (p !== s.p && p.url().startsWith("data:application/pdf")) await p.close();
  const win = await s.app.browserWindow(s.p);
  const key = async k => win.evaluate((w,k)=>{w.webContents.sendInputEvent({type:"keyDown",keyCode:k,modifiers:["control"]});w.webContents.sendInputEvent({type:"keyUp",keyCode:k,modifiers:["control"]});},k);
  await s.prefs({ui_scale_pct:250});
  await key("=");
  await expect.poll(async()=>(await s.native("state")).prefs.ui_scale_pct).toBe(250);
  await key("0"); await key("-");
  await expect.poll(async()=>(await s.native("state")).prefs.ui_scale_pct).toBe(100);
  await capture(s,"patient_feedback");
  const writes = (await s.trace()).requests.filter(r=>r.method==="POST" && r.path.includes(path));
  assert.equal(writes.length,3);
  assert.equal(writes[0].reply_lost,true);
  assert.equal(writes[1].key,writes[2].key);
  assert.deepEqual(writes[1].body,writes[2].body);
  assert.equal(writes[2].replay,"true");
  journal.writes = writes; journal.passed = true; save();
  s.j.passed = true;
  s.pass("Quality pending queue, final review lost reply and GET-only reconciliation, named action original-key replay, summary, named read, independent blank PDF, F1 and bilingual 250%.");
} catch (error) {
  journal.error = error.stack; save();
  if (s) {s.j.error = error.stack;s.save();}
  throw error;
} finally {
  if (s) await s.close();
}
