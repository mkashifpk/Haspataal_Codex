import fs from "node:fs";
import assert from "node:assert/strict";
import { session, expect, help, capture } from "./clinical-test-kit.mjs";

const file = "artifacts/p9a185-journey.json";
assert(!fs.existsSync(file), "Reconcile the original material before further writes.");
const journal = {title:`SYNTHETIC P9A185 training material ${Date.now()}`,pending:null};
const save = () => fs.writeFileSync(file,JSON.stringify(journal,null,2));
save();
let s;
try {
  s = await session("p9a185-ui","demo.quality");
  await s.p.getByRole("navigation").locator('[data-screen-target="education_materials"]').click();
  const root = s.p.locator('[data-screen="education_materials"]');
  const button = name => root.getByRole("button",{name,exact:true});
  const row = root.getByRole("row").filter({hasText:journal.title});
  const read = async () => (await s.native("api",{method:"GET",path:"/education/materials?include_inactive=true"})).find(m=>m.title===journal.title);
  assert.equal(await read(),undefined);
  await button("Add material").click();
  await root.locator('[name="title"]').fill(journal.title);
  await root.locator('[name="topic"]').fill("SYNTHETIC tabletop teaching only");
  await root.locator('[name="kind"]').selectOption("Leaflet");
  await root.locator('[name="language"]').selectOption("Urdu");
  await root.locator('[name="displayed_at"]').fill("Training desk, for DEV verification only");
  await help(s,root.locator('[name="title"]'),"Health education: materials and register");
  await root.locator('input[data-help="ed.save"]').check();
  await s.fault({failPath:"/education/materials",failMethod:"POST",once:true});
  journal.pending = "Create material, original frozen body and key only.";save();
  await button("Save material").click();
  await expect(button("Retry original request")).toBeEnabled();
  await button("Retry original request").click();
  await expect(row).toContainText("Active");
  journal.created = await read();
  assert.equal(journal.created.row_version,1);
  journal.pending = null;save();
  await row.getByRole("button",{name:"Change material",exact:true}).click();
  await root.locator('[name="displayed_at"]').fill("SYNTHETIC retired teaching example");
  await root.locator('[name="active"]').uncheck();
  await root.locator('input[data-help="ed.save"]').check();
  await s.fault({failPath:`/education/materials/${journal.created.material_id}`,failMethod:"PATCH",once:true});
  journal.pending = "Versioned retirement. GET-only reconciliation.";save();
  await button("Save material").click();
  await expect(button("Read current result")).toBeEnabled();
  await expect(button("Retry original request")).toHaveCount(0);
  await button("Read current result").click();
  await button("Result reviewed; return to draft").click();
  await expect(row).toHaveCount(0);
  journal.retired = await read();
  assert.equal(journal.retired.row_version,2);
  assert.equal(journal.retired.is_active,false);
  assert.equal(journal.retired.displayed_at,"SYNTHETIC retired teaching example");
  journal.pending = null;save();
  await root.getByRole("checkbox",{name:"Include retired materials"}).check();
  await expect(row).toContainText("Retired");
  await root.locator('[name="date_from"]').fill("2020-01-01");
  await root.locator('[name="date_to"]').fill("2020-01-31");
  await button("Read period").click();
  await expect(root).toContainText("No education recorded for this period.");
  await capture(s,"education_materials");
  const writes = (await s.trace()).requests.filter(r=>r.method!=="GET"&&r.path.includes("/education/materials"));
  assert.equal(writes.length,3);
  assert.equal(writes[0].key,writes[1].key);
  assert.equal(writes[1].replay,"true");
  assert.equal(writes[2].method,"PATCH");
  assert.equal(writes[2].body.expected_version,1);
  journal.writes=writes;journal.passed=true;save();
  s.j.passed=true;
  s.pass("Fresh education material, original-key replay, versioned retirement with lost reply and GET-only reconciliation, retired filter, period read, contextual F1 and bilingual layout at 250%.");
} catch (error) {
  journal.error=error.stack;save();
  if(s){s.j.error=error.stack;s.save();}
  throw error;
} finally {if(s)await s.close();}
